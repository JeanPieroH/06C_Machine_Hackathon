def extraer_caracteristicas(y, sr):
    """Extrae características avanzadas del audio"""
    mfccs = librosa.feature.mfcc(y=y, sr=sr, n_mfcc=20)

    # Características estadísticas de MFCC
    mfcc_mean = np.mean(mfccs, axis=1)
    mfcc_std = np.std(mfccs, axis=1)
    mfcc_max = np.max(mfccs, axis=1)
    mfcc_min = np.min(mfccs, axis=1)

    zcr = librosa.feature.zero_crossing_rate(y)
    zcr_mean = np.mean(zcr)
    zcr_std = np.std(zcr)

    centroid = librosa.feature.spectral_centroid(y=y, sr=sr)
    centroid_mean = np.mean(centroid)
    centroid_std = np.std(centroid)

    rolloff = librosa.feature.spectral_rolloff(y=y, sr=sr)
    rolloff_mean = np.mean(rolloff)
    rolloff_std = np.std(rolloff)

    bandwidth = librosa.feature.spectral_bandwidth(y=y, sr=sr)
    bandwidth_mean = np.mean(bandwidth)
    bandwidth_std = np.std(bandwidth)

    chroma = librosa.feature.chroma_stft(y=y, sr=sr)
    chroma_mean = np.mean(chroma, axis=1)

    features = np.concatenate([
        mfcc_mean, mfcc_std, mfcc_max, mfcc_min,
        [zcr_mean, zcr_std, centroid_mean, centroid_std,
         rolloff_mean, rolloff_std, bandwidth_mean, bandwidth_std],
        chroma_mean
    ])

    return features

