def buscar_mejores_hiperparametros(x_train_norm, y_train_split, x_val_norm, y_val):
    print("Iniciando búsqueda de hiperparámetros...")
    alphas = [0.0001, 0.0005, 0.001, 0.005, 0.01, 0.05, 0.1]
    lambdas = [0, 0.001, 0.01, 0.05, 0.1, 0.5, 1.0]
    max_iteraciones = [1000, 2000, 3000, 5000]

    mejor_acc = 0
    mejores_params = {}

    # Usar una matriz para visualizar resultados
    resultados = np.zeros((len(alphas), len(lambdas)))

    for i, alpha in enumerate(alphas):
        for j, lambda_reg in enumerate(lambdas):
            # Entrenamos el modelo con estos hiperparámetros
            for iter_num in max_iteraciones:
                w, _, _ = entrenar_regresion_logistica(
                    x_train_norm, y_train_split,
                    x_val_norm, y_val,
                    alpha=alpha,
                    num_iteraciones=iter_num,
                    lambda_reg=lambda_reg
                )

                y_val_pred, _ = predecir(x_val_norm, w)
                val_acc = evaluar_modelo(y_val, y_val_pred)

                print(f"Alpha: {alpha}, Lambda: {lambda_reg}, Iteraciones: {iter_num}, Precisión: {val_acc:.4f}")
                resultados[i, j] = val_acc  # Guardamos para visualización

                if val_acc > mejor_acc:
                    mejor_acc = val_acc
                    mejores_params = {
                        'alpha': alpha,
                        'lambda_reg': lambda_reg,
                        'num_iteraciones': iter_num
                    }

    # Visualizamos los resultados en un heatmap
    plt.figure(figsize=(12, 8))
    sns.heatmap(resultados, annot=True, cmap='viridis',
                xticklabels=lambdas, yticklabels=alphas)
    plt.xlabel('Lambda (Regularización)')
    plt.ylabel('Alpha (Tasa de aprendizaje)')
    plt.title('Precisión de validación para diferentes hiperparámetros')
    plt.show()

    print("\nMejores hiperparámetros encontrados:")
    print(f"Alpha: {mejores_params['alpha']}")
    print(f"Lambda: {mejores_params['lambda_reg']}")
    print(f"Iteraciones: {mejores_params['num_iteraciones']}")
    print(f"Mejor precisión en validación: {mejor_acc:.4f}")

    return mejores_params

